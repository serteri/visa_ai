async function main() {
  console.log("Seeding invitation rounds, occupations, cutoffs, and state allocations...\n");

  // 1. Upsert the Invitation Round
  const round = await prisma.invitationRound.upsert({
    where: { date_visaSubclass: { date: ROUND_DATE, visaSubclass: VISA_SUBCLASS } },
    update: { totalInvited: TOTAL_INVITED, tieBreakDate: TIE_BREAK_DATE },
    create: {
      date: ROUND_DATE,
      visaSubclass: VISA_SUBCLASS,
      totalInvited: TOTAL_INVITED,
      tieBreakDate: TIE_BREAK_DATE,
      notes: "Source: DHA Invitation Rounds Outcomes PDF, 4 June 2026",
    },
  });
  console.log(`✅ Invitation Round: ${round.id} (${VISA_SUBCLASS}, ${TOTAL_INVITED} invites)`);

  // 2. Upsert Occupations + RoundCutoffs
  let occupationsCreated = 0;
  let cutoffsCreated = 0;

  for (const entry of OCCUPATION_CUTOFFS) {
    const occupation = await prisma.occupation.upsert({
      where: { anzscoCode: entry.code },
      update: { title: entry.title },
      create: { anzscoCode: entry.code, title: entry.title },
    });
    if (occupation.createdAt.getTime() === new Date().getTime()) occupationsCreated++;

    const cutoff = await prisma.roundCutoff.upsert({
      where: { roundId_occupationId: { roundId: round.id, occupationId: occupation.id } },
      update: { minimumScore: entry.score },
      create: { roundId: round.id, occupationId: occupation.id, minimumScore: entry.score },
    });
    if (cutoff.createdAt.getTime() === new Date().getTime()) cutoffsCreated++;
  }
  console.log(`✅ Occupations: ${occupationsCreated} created, ${cutoffsCreated} cutoffs created`);

  // 3. Upsert State Allocations
  let allocationsCreated = 0;
  for (const alloc of STATE_ALLOCATIONS) {
    await prisma.stateAllocation.upsert({
      where: {
        programYear_state_visaSubclass: {
          programYear: alloc.programYear,
          state: alloc.state,
          visaSubclass: alloc.visaSubclass,
        },
      },
      update: { allocation: alloc.allocation },
      create: alloc,
    });
    allocationsCreated++;
  }
  console.log(`✅ State Allocations: ${allocationsCreated} upserted`);

  console.log("\n🎉 Seed complete!");
}

main()
  .catch((e) => {
    console.error("Seed failed:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
