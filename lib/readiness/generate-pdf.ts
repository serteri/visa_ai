  function drawTable(
    headers: string[],
    rows: string[][],
    colRatios: number[],
    getCellColor?: (rowIndex: number, colIndex: number, cell: string) => { r: number; g: number; b: number } | null,
    subRows?: Record<number, string>
  ) {
    const tableWidth = contentWidth;
    const colWidths = colRatios.map((ratio) => tableWidth * ratio);
    const cellPadX = 3;
    const cellPadY = 3;
    const bodyLineHeight = 4.6;
    const headerLineHeight = 3.4;

    // Word-wrap every header and size the header band to the tallest one so
    // long localized headers never get truncated or collide.
    const drawHeader = () => {
      const headerLines = headers.map((h, i) =>
        doc.splitTextToSize(safeText(h), Math.max(14, colWidths[i] - cellPadX * 2))
      );
      const headerMaxLines = Math.max(...headerLines.map((lines) => lines.length));
      const headerHeight = Math.max(10, cellPadY * 2 + headerMaxLines * headerLineHeight);

      ensurePageSpace(headerHeight + 6);
      doc.setFillColor(COLORS.primary.r, COLORS.primary.g, COLORS.primary.b);
      doc.roundedRect(margin, yPosition, tableWidth, headerHeight, 1.2, 1.2, "F");

      let cursorX = margin;
      setBoldFont();
      doc.setFontSize(8.5);
      doc.setTextColor(255, 255, 255);
      headers.forEach((h, i) => {
        doc.text(headerLines[i], cursorX + cellPadX, yPosition + headerHeight / 2 + 1.2, {
          maxWidth: colWidths[i] - cellPadX * 2,
          lineHeightFactor: 1.05,
        });
        cursorX += colWidths[i];
      });
      yPosition += headerHeight;
    };

    drawHeader();

    rows.forEach((row, rowIndex) => {
      setBaseFont();
      doc.setFontSize(8.5);
      const wrappedCells = row.map((cell, i) =>
        doc.splitTextToSize(safeText(cell || text.noData), Math.max(14, colWidths[i] - cellPadX * 2))
      );
      const maxLines = Math.max(...wrappedCells.map((lines) => lines.length));
      const rowHeight = Math.max(12, cellPadY * 2 + maxLines * bodyLineHeight);

      if (yPosition + rowHeight > contentBottom) {
        doc.addPage();
        yPosition = margin;
        drawHeader();
      }

      const fill = rowIndex % 2 === 0 ? { r: 255, g: 255, b: 255 } : COLORS.zebra;
      doc.setFillColor(fill.r, fill.g, fill.b);
      doc.rect(margin, yPosition, tableWidth, rowHeight, "F");

      let x = margin;
      row.forEach((cell, i) => {
        const customColor = getCellColor?.(rowIndex, i, cell);
        const color = customColor ?? COLORS.text;
        if (customColor) setBoldFont(); else setBaseFont();
        doc.setFontSize(8.5);
        doc.setTextColor(color.r, color.g, color.b);
        doc.text(wrappedCells[i], x + cellPadX, yPosition + cellPadY + 3.2, {
          maxWidth: colWidths[i] - cellPadX * 2,
          lineHeightFactor: 1.18,
        });
        doc.setDrawColor(COLORS.border.r, COLORS.border.g, COLORS.border.b);
        doc.setLineWidth(0.15);
        if (i > 0) doc.line(x, yPosition, x, yPosition + rowHeight);
        x += colWidths[i];
      });

      doc.setDrawColor(COLORS.border.r, COLORS.border.g, COLORS.border.b);
      doc.setLineWidth(0.2);
      doc.rect(margin, yPosition, tableWidth, rowHeight);
      yPosition += rowHeight;

      // ── Explanation sub-row (full-width, light-gray bg, smaller font) ──
      const subText = subRows?.[rowIndex];
      if (subText && subText.trim().length > 0) {
        const subPadX = 8;
        const subPadY = 4;
        const subLineHeight = 3.8;
        const subWrapped = doc.splitTextToSize(safeText(subText), tableWidth - subPadX * 2);
        const subHeight = Math.max(10, subPadY * 2 + subWrapped.length * subLineHeight);

        if (yPosition + subHeight > contentBottom) {
          doc.addPage();
          yPosition = margin;
          drawHeader();
        }

        // Light gray background spanning full table width
        doc.setFillColor(243, 244, 246); // #f3f4f6
        doc.rect(margin, yPosition, tableWidth, subHeight, "F");

        // Left accent bar for visual distinction
        doc.setFillColor(COLORS.gold.r, COLORS.gold.g, COLORS.gold.b);
        doc.rect(margin, yPosition, 1.5, subHeight, "F");

        // Sub-row text — smaller font, muted color, clear padding
        setBaseFont();
        doc.setFontSize(7);
        doc.setTextColor(120, 130, 145); // muted gray
        doc.text(subWrapped, margin + subPadX, yPosition + subPadY + 2.5, {
          maxWidth: tableWidth - subPadX * 2,
          lineHeightFactor: 1.1,
        });

        // Thin bottom border
        doc.setDrawColor(COLORS.border.r, COLORS.border.g, COLORS.border.b);
        doc.setLineWidth(0.15);
        doc.line(margin, yPosition + subHeight, margin + tableWidth, yPosition + subHeight);
        yPosition += subHeight;
      }
    });

    yPosition += 4;
  }

