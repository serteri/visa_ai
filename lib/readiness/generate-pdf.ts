const INELIGIBLE_RANKING_SUBCLASSES = ["482", "485", "189", "190", "491", "186"] as const;

/** Core Skills Income Threshold — employer-sponsored visa minimum salary (1 July 2026). */
const CSIT_THRESHOLD_AUD = 79423;
